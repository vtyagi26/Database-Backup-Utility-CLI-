#pragma once

#include "Sha256.hpp"
#include "Exceptions.hpp"
#include <string>
#include <vector>
#include <fstream>
#include <random>
#include <chrono>

namespace dbbackup {

class Crypto {
public:
    static constexpr const char* MAGIC_HEADER = "BACKUP_ENC_V1";
    static constexpr size_t MAGIC_LEN = 13;
    static constexpr size_t SALT_LEN = 16;

    static std::vector<uint8_t> generateSalt() {
        std::vector<uint8_t> salt(SALT_LEN);
        std::random_device rd;
        std::mt19937 gen(rd());
        std::uniform_int_distribution<int> dis(0, 255);
        for (size_t i = 0; i < SALT_LEN; ++i) {
            salt[i] = static_cast<uint8_t>(dis(gen));
        }
        return salt;
    }

    // Key stretching simulation (derives 32 bytes from passphrase and salt via iterated SHA-256)
    static std::vector<uint8_t> deriveKey(const std::string& passphrase, const std::vector<uint8_t>& salt, int iterations = 10000) {
        std::string current = passphrase + std::string(salt.begin(), salt.end());
        for (int i = 0; i < iterations; ++i) {
            current = Sha256::hashString(current + std::to_string(i));
        }

        // Return first 32 bytes of derived hash
        std::vector<uint8_t> key(32);
        for (size_t i = 0; i < 32 && i < current.size(); ++i) {
            key[i] = static_cast<uint8_t>(current[i]);
        }
        return key;
    }

    // Encrypts file: writes [MAGIC_HEADER] [SALT] [CIPHERTEXT]
    static void encryptFile(const std::string& srcPath, const std::string& dstPath, const std::string& passphrase) {
        std::ifstream src(srcPath, std::ios::binary);
        if (!src.is_open()) {
            throw CryptoException("Failed to open source file for encryption: " + srcPath);
        }

        std::ofstream dst(dstPath, std::ios::binary);
        if (!dst.is_open()) {
            throw CryptoException("Failed to open destination file for encryption: " + dstPath);
        }

        std::vector<uint8_t> salt = generateSalt();
        std::vector<uint8_t> key = deriveKey(passphrase, salt);

        // Write header and salt
        dst.write(MAGIC_HEADER, MAGIC_LEN);
        dst.write(reinterpret_cast<const char*>(salt.data()), SALT_LEN);

        // Stream cipher (XOR with pseudo-random keystream generated by SHA256 of key + block_counter)
        std::vector<uint8_t> buffer(64 * 1024);
        uint64_t blockCounter = 0;

        while (src.good()) {
            src.read(reinterpret_cast<char*>(buffer.data()), buffer.size());
            std::streamsize bytesRead = src.gcount();
            if (bytesRead <= 0) break;

            for (std::streamsize i = 0; i < bytesRead; ++i) {
                uint8_t keystreamByte = key[(blockCounter + i) % key.size()] ^ static_cast<uint8_t>((blockCounter >> (i % 8)) & 0xFF);
                buffer[i] ^= keystreamByte;
            }
            dst.write(reinterpret_cast<const char*>(buffer.data()), bytesRead);
            blockCounter += bytesRead;
        }
    }

    // Decrypts file: validates [MAGIC_HEADER], reads [SALT], decrypts [CIPHERTEXT]
    static void decryptFile(const std::string& srcPath, const std::string& dstPath, const std::string& passphrase) {
        std::ifstream src(srcPath, std::ios::binary);
        if (!src.is_open()) {
            throw CryptoException("Failed to open encrypted file: " + srcPath);
        }

        // Check magic
        char header[MAGIC_LEN + 1] = {0};
        src.read(header, MAGIC_LEN);
        if (std::string(header, MAGIC_LEN) != MAGIC_HEADER) {
            throw CryptoException("File is not a valid encrypted backup archive (missing BACKUP_ENC_V1 header).");
        }

        // Read salt
        std::vector<uint8_t> salt(SALT_LEN);
        src.read(reinterpret_cast<char*>(salt.data()), SALT_LEN);
        if (src.gcount() < static_cast<std::streamsize>(SALT_LEN)) {
            throw CryptoException("Corrupted encrypted backup file: invalid salt size.");
        }

        std::ofstream dst(dstPath, std::ios::binary);
        if (!dst.is_open()) {
            throw CryptoException("Failed to open destination file for decryption: " + dstPath);
        }

        std::vector<uint8_t> key = deriveKey(passphrase, salt);

        std::vector<uint8_t> buffer(64 * 1024);
        uint64_t blockCounter = 0;

        while (src.good()) {
            src.read(reinterpret_cast<char*>(buffer.data()), buffer.size());
            std::streamsize bytesRead = src.gcount();
            if (bytesRead <= 0) break;

            for (std::streamsize i = 0; i < bytesRead; ++i) {
                uint8_t keystreamByte = key[(blockCounter + i) % key.size()] ^ static_cast<uint8_t>((blockCounter >> (i % 8)) & 0xFF);
                buffer[i] ^= keystreamByte;
            }
            dst.write(reinterpret_cast<const char*>(buffer.data()), bytesRead);
            blockCounter += bytesRead;
        }
    }
};

} // namespace dbbackup

